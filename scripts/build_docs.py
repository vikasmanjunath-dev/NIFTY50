"""Generate the folder READMEs, the report index and the API reference from the code itself, so they cannot drift.
Run after adding or renaming code: python3 scripts/build_docs.py (tests/test_docs.py fails if they are stale)."""
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTE = "<!-- Generated by scripts/build_docs.py. Do not edit by hand. -->\n"
PACKAGES = {
    "data": "Ingestion and the point-in-time data layer.", "features": "Feature families; each uses only what was known at the time.",
    "labels": "Prediction targets.", "validation": "Leakage-free cross-validation.", "models": "Model definitions.",
    "eval": "Metrics, costs and statistical checks.", "monitoring": "Drift and freshness checks.",
    "documents": "Filing retrieval, guarded answers and classification.", "ops": "Serving, audit, kill switch, ledgers and web data.",
}
ROUTES = {
    "GET /": "web app", "GET /sw.js": "offline app shell", "GET /api/overview": "forecasts, upcoming meetings, changes",
    "GET /api/stock/{iid}": "prices, forecasts, track record, meetings, filings", "GET /api/filings": "search filings (`q`, `category`, `instrument` one or comma-separated, `limit`)",
    "GET /api/filings/categories": "most common filing categories", "GET /api/portfolio": "risk of a mix (`holdings=NSE:INFY:50000,...`, `horizon`)",
    "GET /api/sector/{name}": "one sector's stocks and how they move together", "GET /api/backup": "zip of the forward ledgers", "GET /api/model": "progress, reliability, rejected ideas", "GET /api/system": "health, audit, ledgers, forward scorecard",
    "POST /api/refresh": "start the daily refresh (app only)", "GET /api/refresh": "refresh state",
    "POST /v3/analyse": "direction signal or abstention", "POST /v3/evidence": "point-in-time filing evidence (opt-in)",
    "POST /v3/explain": "guarded answer from filings (opt-in)", "POST /v3/classify": "filing event type (opt-in)",
    "GET /v3/volatility": "volatility forecast for one stock", "GET /v3/health": "serving state",
    "POST /v3/admin/kill": "trip the kill switch (token)", "POST /v3/admin/reset": "reset it (token)",
    "GET /v3/audit/verify": "check the audit hash chain", "POST /v3/audit/replay/{seq}": "recompute a logged signal",
    "GET /v3/dashboard": "server-rendered monitoring page",
}


def summary(path: Path) -> str:
    doc = ast.get_docstring(ast.parse(path.read_text())) or ""
    text = " ".join(doc.split("\n\n")[0].split())
    first = re.split(r"(?<=[.])\s+(?=[A-Z])", text)[0] if text else "-"
    return first.replace("|", "\\|")


def table(head, rows):
    return "\n".join([f"| {' | '.join(head)} |", "|" + "---|" * len(head)] + [f"| {' | '.join(r)} |" for r in rows]) + "\n"


def routes_in_code() -> set[str]:
    found = set()
    for f in ("api.py", "web.py"):
        source = (ROOT / "nifty_analyser" / "ops" / f).read_text()
        found |= {f"{m.upper()} {p}" for m, p in re.findall(r'app\.(get|post)\("([^"]+)"', source)}
    return found


def render() -> dict[str, str]:
    out = {}
    pkg = ROOT / "nifty_analyser"
    for name, about in PACKAGES.items():
        rows = [[f"[{p.name}]({p.name})", summary(p)] for p in sorted((pkg / name).glob("*.py")) if p.name != "__init__.py"]
        out[f"nifty_analyser/{name}/README.md"] = f"# {name}\n\n{about}\n\n{table(['Module', 'What it does'], rows)}"
    out["nifty_analyser/README.md"] = "# nifty_analyser\n\n" + table(
        ["Folder", "Purpose"], [[f"[{n}]({n}/README.md)", a] for n, a in PACKAGES.items()] + [["[web](web)", "The web app (HTML, CSS, JavaScript)."]])
    scripts = sorted((ROOT / "scripts").glob("*.py"))
    groups = {"Data": "backfill_", "Build and serve": ("build_", "serve", "train_", "calibrate_", "forecast_", "daily_", "paper_", "label_", "human_", "overnight_"),
              "Studies": "run_"}
    text = "# scripts\n\nRun from the project root with `python3 scripts/<name>`.\n"
    listed = set()
    for title, prefix in groups.items():
        rows = [[f"[{p.name}]({p.name})", summary(p)] for p in scripts if p.name.startswith(prefix) and p.name != "__init__.py"]
        listed |= {r[0] for r in rows}
        text += f"\n## {title}\n\n{table(['Script', 'What it does'], rows)}"
    rest = [[f"[{p.name}]({p.name})", summary(p)] for p in scripts if p.name != "__init__.py" and f"[{p.name}]({p.name})" not in listed]
    out["scripts/README.md"] = text + (f"\n## Other\n\n{table(['Script', 'What it does'], rest)}" if rest else "")
    tests = [[f"[{p.name}]({p.name})", str(len(re.findall(r"^\s*def test_", p.read_text(), re.M)))] for p in sorted((ROOT / "tests").glob("test_*.py"))]
    out["tests/README.md"] = "# tests\n\n`python3 -m pytest -q`. Counts are test functions (parametrised ones run more than once).\n\n" + table(["File", "Tests"], tests)
    sources = {p.name: p.read_text() for p in scripts if p.name != "build_docs.py"}
    rows = []
    for report in sorted(p for p in (ROOT / "reports").iterdir() if p.suffix in (".json", ".md") and p.name != "README.md"):
        stem = re.split(r"_(h\d+|qwen|bge|mxbai|w\d+)", report.stem)[0]
        writers = [n for n, s in sources.items() if report.name in s] or [n for n, s in sources.items() if stem in s]
        rows.append([f"[{report.name}]({report.name})", ", ".join(writers[:3]) or "-"])
    out["reports/README.md"] = "# reports\n\nLocked results. The script column is matched by file name and may be approximate.\n\n" + table(["Report", "Written by"], rows)
    missing, extra = routes_in_code() - set(ROUTES), set(ROUTES) - routes_in_code()
    if missing or extra:
        raise SystemExit(f"API table out of step: undocumented {sorted(missing)}, gone {sorted(extra)}")
    out["docs/API.md"] = ("# API\n\nLocal server only; there is no login.\n\n" +
                          table(["Route", "Purpose"], [[f"`{r}`", d] for r, d in ROUTES.items()]))
    out["docs/README.md"] = "# docs\n\n" + table(["Document", "Contents"], [
        ["[PLAN.md](PLAN.md)", "current plan"], ["[ARCHITECTURE.md](ARCHITECTURE.md)", "how it fits together"],
        ["[OPERATIONS.md](OPERATIONS.md)", "running it day to day"], ["[API.md](API.md)", "routes"], ["[SECURITY.md](SECURITY.md)", "security and privacy"],
        ["[AUC_PLAN.md](AUC_PLAN.md)", "model experiments"], ["[../TRACKER.md](../TRACKER.md)", "build log"], ["*.pdf", "blueprint and reference documents"]])
    return {name: NOTE + body for name, body in out.items()}


if __name__ == "__main__":
    for name, body in render().items():
        (ROOT / name).write_text(body)
    print(f"wrote {len(render())} files")
